# მოიყვანეთ type casting-ის გამოყენების მაგალითები (int, float, str ფუნქციების გამოყენების მაგალითები), ასევე მოიძიეთ ინფორმაცია bool ფუნქციის შესახებ და მოიყვანეთ მისი გამოყენების მაგალითიც.

# int function
print(int("10"))
print(int("300"))

# float function
print(float("40.50"))
print(float(80))

# str function
print(str(10))
print(str(50.356))

# bool function
print(bool("Saba"))
print(bool(0))
