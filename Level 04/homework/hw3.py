# შექმენით ორი ცვლადი: num1 = 47 და num2 = 5.
# გამოიყენეთ /, // და % ოპერატორები და ტერმინალში გამოიტანეთ თითოეული მათგანის შედეგი.
# კომენტარების სახით ახსენით, რა განსხვავებაა ამ სამ ოპერატორს შორის.



num1 = 47
num2 = 5

print(num1 / num2)
print(num1 // num2)
print(num1 % num2)


# /-ვყოფთ რიცხვებს და ტერმინალში გამოდის (float)-ის სახით
# //-ვყოფთ რიცხვებს და ტერმინალში გამოდის (integer)-ის სახით
# %-ამ ოპერატორით ვგებულობთ რიცხვების ნაშთს